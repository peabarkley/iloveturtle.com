// ========== 语言切换逻辑 ==========
let currentLang = localStorage.getItem('iTurtle_lang') || 'zh';

function loadLanguage(lang) {
    const langData = lang === 'zh' ? lang_zh : lang_en;

    // 更新所有 data-i18n 元素
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (langData[key] !== undefined) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.value = langData[key];
            } else {
                el.innerHTML = langData[key];
            }
        }
    });

    // 更新语言切换按钮状态
    document.querySelectorAll('.lang-btn').forEach(btn => {
        const btnLang = btn.getAttribute('data-lang');
        if (btnLang === lang) {
            btn.classList.add('active');
        } else {
            btn.classList.remove('active');
        }
    });

    // 处理双语内容块（适用于文章正文、列表页等）
    document.querySelectorAll('.lang-block-zh, .lang-block-en').forEach(block => {
        if (block.classList.contains(`lang-block-${lang}`)) {
            block.style.display = 'block';
        } else {
            block.style.display = 'none';
        }
    });

    // 保存语言设置
    localStorage.setItem('iTurtle_lang', lang);
    currentLang = lang;
}

// 初始化
document.addEventListener('DOMContentLoaded', () => {
    loadLanguage(currentLang);
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', (e) => {
            const lang = e.target.getAttribute('data-lang');
            loadLanguage(lang);
        });
    });
});